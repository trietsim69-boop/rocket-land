"""Plots + tables from saved data only: runs/*/eval.csv, and results/heatmap_{reward}.csv
(computed once from the final models if missing, then always read back from CSV)."""
import csv
import glob
import os
from multiprocessing import Pool

import gymnasium as gym
import imageio
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from PIL import Image, ImageDraw

from env import X_RANGE, Y_RANGE, StartPosition

REWARDS, SEEDS = ["default", "sparse", "pbrs", "hack"], [0, 1, 2]
GRID_X, GRID_Y, HEAT_EPISODES = np.linspace(*X_RANGE, 8), np.linspace(*Y_RANGE, 5), 10
# Checkpoints nearest to these episode counts; 10**9 = the final one. Random starts learn slower than the fixed start,
# so ep 500/3000 still crash everywhere; untrained / 3000 / final shows the progression instead.
PROGRESSION = dict(run="runs/pbrs_s0_rand", episodes=(1, 3000, 10**9), start=(0.4, 1.2), seed=3)
COLORS = dict(default="tab:gray", sparse="tab:blue", pbrs="tab:green", hack="tab:red")
OUT = "results"


def load(run):
    with open(f"{run}/eval.csv") as f:
        rows = list(csv.DictReader(f))
    return {k: np.array([float(r[k]) for r in rows]) for k in rows[0]}


def rand_runs(reward):
    return [f"runs/{reward}_s{s}_rand" for s in SEEDS if os.path.exists(f"runs/{reward}_s{s}_rand/model.zip")]


def learning_curves():
    fig, ax = plt.subplots(figsize=(9, 5))
    for reward in REWARDS:
        runs = [load(r) for r in rand_runs(reward)]
        if not runs:
            continue
        n = min(len(r["step"]) for r in runs)
        steps, scores = runs[0]["step"][:n], np.stack([r["mean_true_score"][:n] for r in runs])
        mean, std = scores.mean(0), scores.std(0)
        ax.plot(steps, mean, color=COLORS[reward], label=f"{reward} (n={len(runs)})")
        ax.fill_between(steps, mean - std, mean + std, color=COLORS[reward], alpha=0.2)
    ax.axhline(200, ls="--", color="k", lw=1, label="solved (200)")
    ax.set(xlabel="env steps", ylabel="true score (mean ± std over seeds)", ylim=(-500, 320),
           title="Random-start training, scored on the env's original reward")
    ax.legend(loc="lower right")
    fig.tight_layout()
    fig.savefig(f"{OUT}/learning_curves.png", dpi=120)
    plt.close(fig)


def _heat_job(run):
    """Final model of one run over the start grid -> rows (x, y, episodes, landed, mean_true_score)."""
    from stable_baselines3 import PPO

    model, env, rows = PPO.load(f"{run}/model.zip", device="cpu"), StartPosition(gym.make("LunarLander-v3")), []
    for x in GRID_X:
        for y in GRID_Y:
            landed, scores = 0, []
            for k in range(HEAT_EPISODES):
                obs, _ = env.reset(seed=20_000 + k, options={"start": (x, y)})  # seed varies the terrain
                total, done = 0.0, False
                while not done:
                    obs, r, term, trunc, _ = env.step(int(model.predict(obs, deterministic=True)[0]))
                    total += r
                    done = term or trunc
                landed += term and r == 100
                scores.append(total)
            rows.append([run, round(x, 3), round(y, 3), HEAT_EPISODES, landed, float(np.mean(scores))])
    return rows


def heatmap_rows(reward):
    path = f"{OUT}/heatmap_{reward}.csv"
    if not os.path.exists(path):
        with Pool(min(4, len(rand_runs(reward)) or 1)) as pool:
            rows = sum(pool.map(_heat_job, rand_runs(reward)), [])
        with open(path, "w", newline="") as f:
            csv.writer(f).writerows([["run", "x", "y", "episodes", "landed", "mean_true_score"], *rows])
    with open(path) as f:
        return list(csv.DictReader(f))


def heatmap(reward, rows):
    grid = np.zeros((len(GRID_Y), len(GRID_X)))
    for r in rows:
        i, j = np.argmin(abs(GRID_Y - float(r["y"]))), np.argmin(abs(GRID_X - float(r["x"])))
        grid[i, j] += int(r["landed"]) / (int(r["episodes"]) * len({r["run"] for r in rows}))
    fig, ax = plt.subplots(figsize=(8, 4))
    dx, dy = np.diff(GRID_X)[0] / 2, np.diff(GRID_Y)[0] / 2
    im = ax.imshow(grid, origin="lower", cmap="RdYlGn", vmin=0, vmax=1,
                   extent=(GRID_X[0] - dx, GRID_X[-1] + dx, GRID_Y[0] - dy, GRID_Y[-1] + dy), aspect="auto")
    for i, y in enumerate(GRID_Y):
        for j, x in enumerate(GRID_X):
            ax.text(x, y, f"{grid[i, j]:.0%}", ha="center", va="center", fontsize=8)
    ax.set(xlabel="start x (pad at 0)", ylabel="start y (pad at 0)",
           title=f"{reward}: landing success by start position, {grid.mean():.0%} overall")
    fig.colorbar(im, ax=ax, label="success rate")
    fig.tight_layout()
    fig.savefig(f"{OUT}/heatmap_{reward}.png", dpi=120)
    plt.close(fig)


def summary(heat):
    lines = ["# Results", "", "Generated by `python plot.py` from `runs/*/eval.csv` and `results/heatmap_*.csv`.", "",
             "## Random starts (2M steps, seeds " + ", ".join(map(str, SEEDS)) + ")", "",
             f"Final models on the {len(GRID_X)}×{len(GRID_Y)} start grid × {HEAT_EPISODES} episodes; "
             "mean ± std over seeds. First ≥ 200 = first eval where the seed-mean curve reaches 200.", "",
             "| reward | seeds | true score | success | first ≥ 200 |", "|---|---|---|---|---|"]
    for reward in REWARDS:
        rows = heat.get(reward)
        if not rows:
            continue
        runs = sorted({r["run"] for r in rows})
        score = [np.mean([float(r["mean_true_score"]) for r in rows if r["run"] == run]) for run in runs]
        success = [sum(int(r["landed"]) for r in rows if r["run"] == run) / sum(int(r["episodes"]) for r in rows if r["run"] == run) for run in runs]
        curves = [load(run) for run in runs]
        n = min(len(c["step"]) for c in curves)
        mean = np.mean([c["mean_true_score"][:n] for c in curves], 0)
        hit = np.flatnonzero(mean >= 200)
        first = f"{curves[0]['step'][hit[0]] / 1e6:.2f}M" if len(hit) else "never"
        lines.append(f"| {reward} | {len(runs)} | {np.mean(score):.0f} ± {np.std(score):.0f} | "
                     f"{np.mean(success):.0%} ± {np.std(success):.0%} | {first} |")
    lines += ["", "## Fixed start (Phase 2, seed 0, 1M steps)", "",
              "Last eval row (10 deterministic episodes). λ = GAE λ; 0.9 is the project default.", "",
              "| run | true score | success | first ≥ 200 |", "|---|---|---|---|"]
    for run in sorted(glob.glob("runs/*_s0*")):
        if run.endswith("_rand"):
            continue
        c = load(run)
        hit = np.flatnonzero(c["mean_true_score"] >= 200)
        first = f"{c['step'][hit[0]] / 1e6:.2f}M" if len(hit) else "never"
        lines.append(f"| {os.path.basename(run)} | {c['mean_true_score'][-1]:.0f} | {c['success_rate'][-1]:.0%} | {first} |")
    with open(f"{OUT}/summary.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def progression():
    """Rollouts from a few checkpoints, side by side, above the learning curve with matching markers."""
    from stable_baselines3 import PPO

    run, c = PROGRESSION["run"], load(PROGRESSION["run"])
    saved = sorted(int(os.path.basename(p)[5:-4]) for p in glob.glob(f"{run}/ckpt_*.zip"))
    picks = [min(saved, key=lambda e: abs(e - want)) for want in PROGRESSION["episodes"]]

    panels = []
    for ep in picks:
        model = PPO.load(f"{run}/ckpt_{ep}.zip", device="cpu")
        env = StartPosition(gym.make("LunarLander-v3", render_mode="rgb_array"))
        obs, _ = env.reset(seed=PROGRESSION["seed"], options={"start": PROGRESSION["start"]})
        frames, total, done = [env.render()[::2, ::2]], 0.0, False
        while not done:
            obs, r, term, trunc, _ = env.step(int(model.predict(obs, deterministic=True)[0]))
            total += r
            done = term or trunc
            frames.append(env.render()[::2, ::2])
        label = f"episode {ep}: {'landed' if term and r == 100 else 'crashed' if term else 'timeout'} ({total:.0f})"
        panels.append((frames, label))

    fig, ax = plt.subplots(figsize=(9, 2.6), dpi=100)
    ax.plot(c["episodes_so_far"], c["mean_true_score"], color=COLORS["pbrs"])
    ax.axhline(200, ls="--", color="k", lw=1)
    for k, ep in enumerate(picks):
        y = c["mean_true_score"][np.argmin(abs(c["episodes_so_far"] - ep))]
        ax.plot(ep, y, "o", color="k")
        ax.annotate(str(k + 1), (ep, y), textcoords="offset points", xytext=(5, 5))
    ax.set(xlabel="training episodes", ylabel="true score", ylim=(-1200, 320))
    fig.tight_layout()
    fig.canvas.draw()
    curve = np.asarray(fig.canvas.buffer_rgba())[..., :3]
    plt.close(fig)

    gif = []
    for t in range(0, max(len(f) for f, _ in panels), 3):  # every 3rd frame keeps the GIF small
        row = []
        for k, (frames, label) in enumerate(panels):
            img = Image.fromarray(frames[min(t, len(frames) - 1)])
            ImageDraw.Draw(img).text((5, 5), f"{k + 1}. {label}", fill=(255, 255, 255))
            row.append(np.asarray(img))
        top = np.concatenate(row, axis=1)
        gif.append(np.concatenate([top, np.asarray(Image.fromarray(curve).resize((top.shape[1], curve.shape[0])))], axis=0))
    imageio.mimsave(f"{OUT}/progression.gif", gif, duration=60, loop=0)


if __name__ == "__main__":
    if not glob.glob("runs/*/eval.csv"):  # e.g. a fresh clone: don't overwrite the committed results/ with empty ones
        raise SystemExit("plot.py: no runs/*/eval.csv found, nothing to plot. Train first (train.py) or keep results/ as committed.")
    os.makedirs(OUT, exist_ok=True)
    learning_curves()
    heat = {reward: heatmap_rows(reward) for reward in REWARDS if rand_runs(reward)}
    for reward, rows in heat.items():
        heatmap(reward, rows)
    summary(heat)
    if glob.glob(f"{PROGRESSION['run']}/ckpt_*.zip"):  # checkpoints are never committed, so a clone keeps the committed GIF
        progression()
    print("wrote", sorted(os.listdir(OUT)))
